#!/usr/bin/env python3
"""
Give the right size to functions whose jump table targets lie after the end splat chose (spimdisasm ends a function at
the first "jr $ra" that is not followed by a known branch target; the cases reached only through a jump table are then
left outside any function, and N64Recomp fails with "Failed to determine size of jump table").

Reads the splat output (build/splat/asm), writes config/symbol_sizes.txt (second symbol_addrs file of config/splat.yaml):
    func_<vram>_<rom> = 0x<vram>; // type:func rom:0x<rom> size:0x<size>
The new end of a function = start of the next real function (glabel) after its last jump table target.

Usage (after a first `splat split`): python tools/fix_jtbl_sizes.py, then gen_splat + splat split again.
"""
import bisect
import pathlib
import re
from collections import defaultdict

ROOT = pathlib.Path(__file__).resolve().parent.parent
ASM = ROOT / "build" / "splat" / "asm"
OUT = ROOT / "config" / "symbol_sizes.txt"

NONMATCH_RE = re.compile(r"^nonmatching (\w+), (0x[0-9A-Fa-f]+)")
GLABEL_RE = re.compile(r"^glabel (\w+)")
ROM_OF = re.compile(r"_([0-9A-F]+)$")  # symbol_name_format $VRAM_$ROM
JTBL_REF_RE = re.compile(r"%lo\((jtbl_\w+)\)")
DLABEL_RE = re.compile(r"^dlabel (jtbl_\w+)")
WORD_RE = re.compile(r"\.word (\.?L?\w+?_[0-9A-F]+|func_\w+)\s*$")


def rom_of(sym):
    return int(ROM_OF.search(sym).group(1), 16)


def main():
    funcs = {}  # name -> (rom start, size)
    uses = defaultdict(set)  # function name -> jump tables it reads
    tables = defaultdict(list)  # jump table -> target roms
    for path in ASM.rglob("*.s"):
        size, cur, jt = {}, None, None
        for line in path.read_text(encoding="utf-8").splitlines():
            if m := NONMATCH_RE.match(line):
                size[m.group(1)] = int(m.group(2), 16)
            elif m := GLABEL_RE.match(line):
                cur = m.group(1)
                if cur.startswith("func_") and cur in size:
                    funcs[cur] = (rom_of(cur), size[cur])
            elif m := DLABEL_RE.match(line):
                jt = m.group(1)
            elif line.startswith(("enddlabel", "dlabel")):
                jt = None
            else:
                if cur and (m := JTBL_REF_RE.search(line)):
                    uses[cur].add(m.group(1))
                if jt and (m := WORD_RE.search(line)):
                    tables[jt].append(rom_of(m.group(1)))
    starts = sorted(r for r, _ in funcs.values())
    lines = []
    for name, jts in sorted(uses.items()):
        if name not in funcs:
            continue  # already named function (libultra...): not handled, reported below
        start, size = funcs[name]
        last = max((t for jt in jts for t in tables.get(jt, [])), default=0)
        if last < start + size:
            continue
        i = bisect.bisect_right(starts, last)
        if i == len(starts):
            print(f"  {name}: last case 0x{last:X} after the last function, not resized")
            continue
        nxt = starts[i]
        vram = int(name.split("_")[1], 16)
        lines.append(f"{name} = 0x{vram:08X}; // type:func rom:0x{start:X} size:0x{nxt - start:X}")
    named = [n for n in uses if n not in funcs]
    OUT.write_text("// Generated by tools/fix_jtbl_sizes.py: real size of functions whose jump table cases follow their first jr $ra.\n"
                   + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(lines)} functions resized -> {OUT.relative_to(ROOT)}")
    if named:
        print("not checked (named functions, add size: by hand if N64Recomp fails):", ", ".join(sorted(named)))


if __name__ == "__main__":
    main()
