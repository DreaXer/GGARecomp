#!/usr/bin/env python3
r"""
Generate config/splat.yaml for GGA (US) from the decompressed ROM and config/rommy.json.

Code segments (see notes/OVERLAYS.md):
    main code      ROM 0x1000, VRAM 0x80000400, BSS up to 0x800C7310
    game file 6    VRAM 0x800C7B10 (permanent)
    game files 8/9/10   VRAM 0x801738A0 (overlays, exclusive_ram_id "ovl")
    TLB modules    VRAM 0x08000000 (exclusive_ram_id "tlb"): files whose load address in the game table 0x80026B00 is
                   0x08000000 and that contain at least one "jr $ra"
Everything else is a "bin" segment. Segment names use the GAME file index (1-based): file_<idx>.
Each code segment = [asm] up to the end of the code, then [data], then BSS (load size from the game table).

Usage (Python 3.14 is fine, standard library only):
    python tools/gen_splat.py
then, with the splat venv:
    .\.venv\Scripts\python.exe -m splat split config\splat.yaml
"""
import hashlib
import json
import pathlib
import struct

ROOT = pathlib.Path(__file__).resolve().parent.parent
ROM_PATH = ROOT / "baserom.us.decompressed.z64"

MAIN_ROM, MAIN_VRAM, MAIN_END_VRAM, MAIN_BSS_END = 0x1000, 0x80000400, 0x8003ED10, 0x800C7310
LOAD_TABLE = 0x80026B00  # {start, end} per game file, entry idx-1
JR_RA = 0x03E00008
# RSP code (scalar + vector, jumps to IMEM 0x04001xxx) inside main .text, measured in the splat asm 2026-10-19: keep it out of the CPU code
MAIN_RSP_ROM = (0x25070, 0x26630)


def ram_to_rom(addr):
    return addr - MAIN_VRAM + MAIN_ROM


def words(b):
    return struct.unpack(f">{len(b) // 4}I", b[: len(b) // 4 * 4])


def is_prologue(w):
    return (w & 0xFFFF8000) == 0x27BD8000  # addiu $sp, $sp, -X


def code_end(ws):
    """Byte offset where code stops: after the last "jr $ra" + delay slot, aligned to 16.
    A function placed right after it (prologue within the padding) extends the code.
    shortcut: a last function that ends without "jr $ra" (infinite loop, tail jump) is left in [data]; check the asm if splat warns."""
    jrs = [i for i, w in enumerate(ws) if w == JR_RA]
    if not jrs:
        return 0
    end = jrs[-1] + 2
    while True:
        end = (end + 3) & ~3  # 16 bytes = 4 words
        nxt = next((i for i in range(end, min(end + 4, len(ws))) if ws[i]), None)
        if nxt is None or not is_prologue(ws[nxt]):
            return end * 4
        later = [i for i in jrs if i > nxt]
        if not later:
            return end * 4
        end = later[0] + 2


def main():
    rom = ROM_PATH.read_bytes()
    files = json.loads((ROOT / "config" / "rommy.json").read_text())["files"]
    # first jump table of each segment (spimdisasm only analyses jump tables in rodata), see config/rodata_starts.txt
    ro_path = ROOT / "config" / "rodata_starts.txt"
    rodata = [int(x, 16) for x in ro_path.read_text().split() if x.startswith("0x")] if ro_path.exists() else []
    table = lambda g, k: struct.unpack(">I", rom[ram_to_rom(LOAD_TABLE + (g - 1) * 8 + 4 * k):][:4])[0]

    code = []  # (rom start, name, vram, size, load size, exclusive id, code end)
    mw = words(rom[MAIN_ROM : ram_to_rom(MAIN_END_VRAM)])
    code.append((MAIN_ROM, "main", MAIN_VRAM, len(mw) * 4, MAIN_BSS_END - MAIN_VRAM, None, code_end(mw)))
    for g in range(1, len(files) + 1):
        f = files[g - 1]
        assert f["index"] == g - 1
        start, end = table(g, 0), table(g, 1)
        if f["new_size"] == 0:
            continue
        ws = words(rom[f["new_offset"] : f["new_offset"] + f["new_size"]])
        if start == 0x800C7B10:
            excl = None
        elif start == 0x801738A0:
            excl = "ovl"
        elif start == 0x08000000 and JR_RA in ws:
            excl = "tlb"
        else:
            continue
        code.append((f["new_offset"], f"file_{g}", start, f["new_size"], end - start, excl, code_end(ws)))

    out = [
        "# Generated by tools/gen_splat.py - do not edit by hand, edit the script and regenerate.",
        "name: Goemon's Great Adventure (USA) - decompressed",
        f"sha1: {hashlib.sha1(rom).hexdigest()}",
        "",
        "options:",
        "  basename: ga",
        "  compiler: IDO",
        "  platform: n64",
        "  header_encoding: ASCII",
        "  base_path: ..",
        "  target_path: baserom.us.decompressed.z64",
        "  build_path: build",
        "  elf_path: build/ga.elf",
        "  ld_script_path: build/splat/ga.ld",
        "  undefined_funcs_auto_path: build/splat/undefined_funcs_auto.ld",
        "  undefined_syms_auto_path: build/splat/undefined_syms_auto.ld",
        "  asm_path: build/splat/asm",
        "  src_path: build/splat/src",
        "  asset_path: build/splat/bin",
        "  symbol_addrs_path:",
        "    - config/symbol_addrs.txt",
        "    - config/symbol_sizes.txt  # generated by tools/fix_jtbl_sizes.py",
        "  symbol_name_format: $VRAM_$ROM  # 311 modules share VRAM 0x08000000: the ROM suffix keeps names unique",
        "  find_file_boundaries: True",
        "  migrate_rodata_to_functions: False",
        "  generate_asm_macros_files: False  # keep OUR include/macro.inc (no .ent/.aent/.end: clang refuses them)",
        "  # no string guessing: Shift-JIS strings were written back as UTF-8 (more bytes) and shifted every section after file 6",
        "  rodata_string_guesser_level: 0",
        "  data_string_guesser_level: 0",
        "",
        "segments:",
        "  - name: header",
        "    type: header",
        "    start: 0x0",
        "",
        "  - name: ipl3",
        "    type: bin",
        "    start: 0x40",
        "",
    ]
    pos = 0x1000
    for rstart, name, vram, size, load, excl, cend in code:
        if rstart > pos:
            out += [f"  - name: bin_{pos:X}", "    type: bin", f"    start: 0x{pos:X}", ""]
        assert rstart >= pos and rstart % 16 == 0 and size % 16 == 0, name
        bss = load - size
        assert bss >= 0, name
        out += [f"  - name: {name}", "    type: code", f"    start: 0x{rstart:X}", f"    vram: 0x{vram:X}"]
        if bss:
            out.append(f"    bss_size: 0x{bss:X}")
        if excl:
            out += ["    overlay: yes", f"    exclusive_ram_id: {excl}"]
        out += ["    subalign: 16", "    subsegments:", f"    - [0x{rstart:X}, asm]"]
        if name == "main":
            assert MAIN_ROM + cend == MAIN_RSP_ROM[1], "main code end moved: re-check MAIN_RSP_ROM"
            out.append(f"    - [0x{MAIN_RSP_ROM[0]:X}, bin, rsp_text]")
        if cend < size:
            ro = [max(h & ~0xF, rstart + cend) for h in rodata if rstart + cend <= h < rstart + size]
            assert len(ro) <= 1, name
            if not ro or ro[0] > rstart + cend:
                out.append(f"    - [0x{rstart + cend:X}, data]")
            if ro:
                out.append(f"    - [0x{ro[0]:X}, rodata]")
        if bss:
            out.append(f"    - {{ start: 0x{rstart + size:X}, type: bss, vram: 0x{vram + size:X} }}")
        out.append("")
        pos = rstart + size
    out += [f"  - name: bin_{pos:X}", "    type: bin", f"    start: 0x{pos:X}", "", f"  - [0x{len(rom):X}]", ""]

    (ROOT / "config" / "splat.yaml").write_text("\n".join(out), encoding="utf-8")
    sym = ROOT / "config" / "symbol_addrs.txt"
    if not sym.exists():
        sym.write_text("entrypoint = 0x80000400; // type:func\n", encoding="utf-8")
    n = {k: sum(1 for c in code if c[5] == k) for k in (None, "ovl", "tlb")}
    print(f"config/splat.yaml: {len(code)} code segments (fixed {n[None]}, ovl {n['ovl']}, tlb {n['tlb']})")
    for c in code[:5]:
        print(f"  {c[1]}: code {c[6]:#x} / {c[3]:#x}")


if __name__ == "__main__":
    main()
